"""Generate the data headers the C++ plugin embeds, plus reference vectors for its tests.

Outputs
  src/generated/emulsion_data.h   look LUTs (33^3, uint16), base curve table, input matrices
  tests/ref/decode_vectors.txt    camera log code value -> scene linear (camera gamut), from colour-science
  tests/ref/pixel_vectors.txt     full per-pixel pipeline reference (glow and grain off)
"""
import os
import sys
import numpy as np
import colour

sys.path.insert(0, os.path.dirname(__file__))
import looks as LK  # noqa: E402
import cneg_look as CL  # noqa: E402
import base_render as BR  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CS = colour.RGB_COLOURSPACES
M = colour.models

# id, label, gamut, decode(code)->linear (camera gamut), display-referred?
PROFILES = [
    ('DaVinci Intermediate / DWG', 'DaVinci Wide Gamut', M.oetf_inverse_DaVinciIntermediate, False),
    ('Rec.709 (Gamma 2.4)', 'ITU-R BT.709', None, True),
    ('Sony S-Log3 / S-Gamut3.Cine', 'S-Gamut3.Cine', M.log_decoding_SLog3, False),
    ('Sony S-Log3 / S-Gamut3', 'S-Gamut3', M.log_decoding_SLog3, False),
    ('Fujifilm F-Log2 / F-Gamut', 'F-Gamut', M.log_decoding_FLog2, False),
    ('Fujifilm F-Log2 C / F-Gamut C', 'F-Gamut C', M.log_decoding_FLog2, False),
    ('Fujifilm F-Log / F-Gamut', 'F-Gamut', M.log_decoding_FLog, False),
    ('Apple Log (iPhone)', 'ITU-R BT.2020', M.log_decoding_AppleLogProfile, False),
    ('Panasonic V-Log / V-Gamut', 'V-Gamut', M.log_decoding_VLog, False),
    ('Canon Log 3 / Cinema Gamut', 'Cinema Gamut', M.log_decoding_CanonLog3, False),
    ('ARRI LogC3 (EI 800) / AWG3', 'ARRI Wide Gamut 3', M.log_decoding_ARRILogC3, False),
    ('ARRI LogC4 / AWG4', 'ARRI Wide Gamut 4', M.log_decoding_ARRILogC4, False),
    ('Blackmagic Film Gen 5', 'Blackmagic Wide Gamut', M.oetf_inverse_BlackmagicFilmGeneration5, False),
    ('Nikon N-Log', 'N-Gamut', M.log_decoding_NLog, False),
    ('DJI D-Log / D-Gamut', 'DJI D-Gamut', M.log_decoding_DJIDLog, False),
]
DISPLAY_SCALE = 1.44   # Rec.709 input: display-linear * 1.44 puts code 0.42 at 0.18 (mid grey)


def to2020(gamut):
    return colour.matrix_RGB_to_RGB(CS[gamut], CS['ITU-R BT.2020'], chromatic_adaptation_transform=None)


def decode(i, code):
    label, gamut, fn, disp = PROFILES[i]
    code = np.asarray(code, dtype=np.float64)
    if disp:
        return np.sign(code) * np.abs(code) ** 2.4 * DISPLAY_SCALE
    return np.asarray(fn(code), dtype=np.float64)


def fmt(v):
    t = f'{float(v):.9g}'
    if not any(ch in t for ch in '.en'):
        t += '.0'
    return t + 'f'


def main():
    gen = os.path.join(ROOT, 'src', 'generated')
    refd = os.path.join(ROOT, 'tests', 'ref')
    os.makedirs(gen, exist_ok=True)
    os.makedirs(refd, exist_ok=True)

    # ---------------------------------------------------------- looks
    luts = []
    for name, _ in LK.LOOKS:
        lut = LK.build_lut(LK.make_look(name), 33)            # [b, g, r, 3] cube order
        luts.append((name, np.clip(np.round(lut * 65535), 0, 65535).astype(np.uint16)))

    out = []
    out.append('// Generated by tools/gen_cpp_data.py - do not edit.\n#pragma once\n#include <cstdint>\n\nnamespace emu { namespace data {\n')
    out.append(f'static const int kLutSize = 33;\nstatic const int kLookCount = {len(luts)};\n')
    out.append('static const char* const kLookNames[kLookCount] = {' + ', '.join(f'"{n}"' for n, _ in luts) + '};\n')
    out.append('// index = ((b * 33 + g) * 33 + r) * 3 + channel, value / 65535\n')
    out.append(f'static const uint16_t kLookLuts[kLookCount][33 * 33 * 33 * 3] = {{\n')
    for name, q in luts:
        flat = q.reshape(-1)
        out.append(f'  {{ // {name}\n')
        for k in range(0, len(flat), 24):
            out.append('    ' + ','.join(str(int(v)) for v in flat[k:k + 24]) + ',\n')
        out.append('  },\n')
    out.append('};\n\n')

    # ---------------------------------------------------------- base curve
    out.append(f'static const float kCurveStopMin = {fmt(BR.STOP_MIN)};\nstatic const float kCurveStopMax = {fmt(BR.STOP_MAX)};\n')
    out.append(f'static const int kCurveSize = {BR.CURVE_N};\nstatic const float kCurve[kCurveSize] = {{\n')
    for k in range(0, BR.CURVE_N, 8):
        out.append('  ' + ', '.join(fmt(v) for v in BR.CURVE_TABLE[k:k + 8]) + ',\n')
    out.append('};\n\n')
    m = BR.M_2020_TO_709
    out.append('static const float kRec2020ToRec709[9] = {' + ', '.join(fmt(v) for v in m.reshape(-1)) + '};\n')

    # ---------------------------------------------------------- input profiles
    out.append(f'\nstatic const int kInputCount = {len(PROFILES)};\n')
    out.append('static const char* const kInputNames[kInputCount] = {\n' + ''.join(f'  "{p[0]}",\n' for p in PROFILES) + '};\n')
    out.append('// camera gamut (linear) -> linear Rec.2020, row-major\n')
    out.append('static const float kInputToRec2020[kInputCount][9] = {\n')
    for label, gamut, fn, disp in PROFILES:
        mm = to2020(gamut).reshape(-1)
        out.append('  {' + ', '.join(fmt(v) for v in mm) + f'}}, // {label}\n')
    out.append('};\n')
    out.append(f'static const float kDisplayScale = {fmt(DISPLAY_SCALE)};\n')
    out.append('\n}} // namespace emu::data\n')
    with open(os.path.join(gen, 'emulsion_data.h'), 'w') as f:
        f.write(''.join(out))

    # ---------------------------------------------------------- decode vectors
    codes = np.concatenate([np.linspace(-0.05, 1.05, 45), [0.0929, 0.14, 0.1005, 0.181, 0.0274, 0.3, 0.41, 0.4635]])
    with open(os.path.join(refd, 'decode_vectors.txt'), 'w') as f:
        for i in range(len(PROFILES)):
            for c in codes:
                f.write(f'{i} {c:.9g} {float(decode(i, c)):.12g}\n')

    # ---------------------------------------------------------- per-pixel pipeline vectors
    rng = np.random.default_rng(7)
    n = 3000
    rows = []
    for i in range(len(PROFILES)):
        code = rng.random((n, 3)) * 1.02 - 0.01
        lin = np.stack([decode(i, code[:, c]) for c in range(3)], -1)
        lin2020 = lin @ to2020(PROFILES[i][1]).T
        for look_idx in range(len(LK.LOOKS)):
            exp = float(rng.choice([-1.0, 0.0, 0.5]))
            con = float(rng.choice([0.8, 1.0, 1.25]))
            sat = float(rng.choice([0.6, 1.0, 1.3]))
            stren = float(rng.choice([0.0, 0.5, 1.0]))
            sel = slice(look_idx * 40, look_idx * 40 + 40)
            x = lin2020[sel]
            if PROFILES[i][3]:
                base = display_path(x, exp, con)
            else:
                base = BR.base_render(x, exp, con)
            lut = luts[look_idx][1].astype(np.float64) / 65535.0
            looked = CL.apply_lut(lut, np.clip(base, 0, 1))
            mix = base + stren * (looked - base)
            Y = mix @ BR.Y709
            res = np.clip(Y[:, None] + sat * (mix - Y[:, None]), 0, 1)
            for k in range(x.shape[0]):
                rows.append((i, look_idx, exp, con, sat, stren, *code[sel][k], *res[k]))
    with open(os.path.join(refd, 'pixel_vectors.txt'), 'w') as f:
        for r in rows:
            f.write(' '.join(f'{v:.9g}' for v in r) + '\n')
    print('looks', [n for n, _ in luts])
    print('header bytes', os.path.getsize(os.path.join(gen, 'emulsion_data.h')))
    print('pixel vectors', len(rows))


def display_path(lin2020, exposure, contrast):
    """Rec.709 input path (no tone render): pseudo-scene linear -> exposure/contrast -> back to code."""
    x = lin2020 * 2.0 ** exposure
    x = np.where(x > 0, 0.18 * (np.maximum(x, 1e-12) / 0.18) ** contrast, x)
    d709 = (x @ BR.M_2020_TO_709.T) / DISPLAY_SCALE
    d709 = np.clip(d709, 0.0, 1.0)
    return d709 ** (1 / 2.4)


if __name__ == '__main__':
    main()
