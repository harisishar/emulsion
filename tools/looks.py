MONO_CURVE = [(0.00, 0.010), (0.05, 0.025), (0.10, 0.058), (0.20, 0.140), (0.35, 0.305), (0.50, 0.500),
              (0.65, 0.690), (0.80, 0.845), (0.90, 0.925), (0.96, 0.962), (1.00, 0.975)]


class MonoLook:
    """Panchromatic black & white: weighted linear-light mix, then a contrasty print curve."""
    def __init__(self, weights=(0.30, 0.59, 0.11)):
        from scipy.interpolate import PchipInterpolator
        self.w = np.array(weights)
        x, y = zip(*MONO_CURVE)
        self.curve = PchipInterpolator(x, y)

    def __call__(self, rgb):
        lin = CL.srgb_to_lin(np.clip(rgb, 0, 1))
        y = np.clip(lin @ self.w, 0, 1)
        v = np.clip(self.curve(CL.lin_to_srgb(y)), 0, 1)
        return np.repeat(v[..., None], 3, axis=-1)


class Identity:
    def __call__(self, rgb):
        return np.clip(rgb, 0, 1)


LOOKS = [
    ('Cinematic Neg', _cinematic_neg),
    ('Tungsten 500 Print', _tungsten_print),
    ('Portrait 400', _portrait_400),
    ('Slide 100', _slide_100),
    ('Sunny 200 Faded', _sunny_200),
    ('Mono 400', None),
    ('Neutral (no look)', None),
]


def make_look(name):
    for n, fn in LOOKS:
        if n == name:
            if n == 'Mono 400':
                return MonoLook()
            if n.startswith('Neutral'):
                return Identity()
            return CL.Look(copy.deepcopy(fn()))
    raise KeyError(name)


def build_lut(look, n=33):
    return CL.build_lut(look, n)  # [b, g, r, 3]
